export function getPlaceBySlug(slug: string): Place | undefined {
  return astanaPlaces.find((place) => place.slug === slug);
}

export function getPlaceById(id: string): Place | undefined {
  return astanaPlaces.find((place) => place.id === id);
}

export function getNearbyPlaces(placeId: string): Place[] {
  const place = getPlaceById(placeId);
  if (!place || !place.nearbyPlaceIds) return [];

  return place.nearbyPlaceIds
    .map((id) => getPlaceById(id))
    .filter((p): p is Place => p !== undefined);
}
